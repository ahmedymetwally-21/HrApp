export function getStepRoleLabel(lang: Language, step: ApprovalStepRole): string {
  if (step === 'section_manager') return getRoleLabel(lang, UserRole.SectionManager);
  if (step === 'hr_admin') return lang === 'en' ? 'HR' : getRoleLabel(lang, UserRole.HRAdmin);
  return getRoleLabel(lang, UserRole.MainManager);
}

